# Load
# ---------------------------------------------------------------------------


def load_capsule(path: str | Path) -> LoadedCapsule:
    """Read a capsule directory and return a ``LoadedCapsule``."""
    capsule_dir = Path(path).resolve()
    if not capsule_dir.is_dir():
        raise FileNotFoundError(f"Capsule directory not found: {capsule_dir}")

    manifest_path = capsule_dir / "manifest.toml"
    if not manifest_path.is_file():
        raise FileNotFoundError(
            f"No manifest.toml under {capsule_dir}; not a capsule directory."
        )
    manifest = _read_toml(manifest_path)

    capsule_section = manifest.get("capsule", {})
    fmt_version = capsule_section.get("format_version", "0.0")
    if fmt_version != CAPSULE_FORMAT_VERSION:
        raise ValueError(
            f"Unsupported capsule format_version {fmt_version!r}; "
            f"this build understands {CAPSULE_FORMAT_VERSION!r}. "
            "Capsule migrations land in Phase 2."
        )

    # Experiment lives at configs/run_config.yaml (it serializes the full
    # Experiment, ModelSpec inlined, by design of Workstream 1A).
    run_config_path = capsule_dir / "configs" / "run_config.yaml"
    if not run_config_path.is_file():
        raise FileNotFoundError(f"No configs/run_config.yaml under {capsule_dir}.")
    experiment = Experiment.load_yaml(run_config_path)

    diagnostics_path = capsule_dir / "results" / "diagnostics.json"
    if not diagnostics_path.is_file():
        raise FileNotFoundError(f"No results/diagnostics.json under {capsule_dir}.")
    payload = json.loads(diagnostics_path.read_text(encoding="utf-8"))

    provenance_path = capsule_dir / "provenance" / "provenance.lock"
    provenance = _read_toml(provenance_path) if provenance_path.is_file() else {}

    return LoadedCapsule(
        path=capsule_dir,
        name=capsule_section.get("name", capsule_dir.stem),
        format_version=fmt_version,
        experiment=experiment,
        diagnostics={k: list(v) for k, v in payload.get("diagnostics", {}).items()},
        placeholders=list(payload.get("placeholders", [])),
        final_simulation_time=float(payload.get("final_simulation_time", 0.0)),
        state=str(payload.get("state", "unknown")),
        elapsed_seconds=float(payload.get("elapsed_seconds", 0.0)),
        provenance=provenance,
    )


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _default_capsule_name(experiment: Experiment, result: RunResult) -> str:
    base = experiment.model_spec.model.name.replace(" ", "_")
    return f"{base}-{result.run_id[:8]}"


def _utc_now_iso() -> str:
    from datetime import UTC, datetime

    return datetime.now(UTC).isoformat(timespec="microseconds")


def _write_toml(path: Path, data: dict[str, Any]) -> None:
    """Tiny TOML writer adequate for the Phase 1 manifest shape.

    Avoids adding a runtime dep on ``tomli_w`` for the few cases we have. The
    schema is flat (one level of nested dicts), so a hand-rolled writer is
    safe. Phase 2 may swap to tomli_w if the schema grows.
    """
    lines: list[str] = []
    top_scalars: list[tuple[str, Any]] = []
    nested: list[tuple[str, dict[str, Any]]] = []
    for key, value in data.items():
        if isinstance(value, dict):
            nested.append((key, value))
        else:
            top_scalars.append((key, value))
    for key, value in top_scalars:
        lines.append(f"{key} = {_toml_value(value)}")
    for section, body in nested:
        lines.append("")
        lines.append(f"[{section}]")
        for key, value in body.items():
            lines.append(f"{key} = {_toml_value(value)}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _toml_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        # Single-line; escape backslash and quotes per TOML basic strings.
        escaped = value.replace("\\", "\\\\").replace('"', '\\"')
        return f'"{escaped}"'
    if isinstance(value, list):
        rendered = ", ".join(_toml_value(v) for v in value)
        return f"[{rendered}]"
    raise TypeError(f"Unsupported TOML value type for capsule manifest: {type(value).__name__}")


def _read_toml(path: Path) -> dict[str, Any]:
    """Parse TOML using the stdlib ``tomllib`` (Python 3.11+)."""
    import tomllib

    with path.open("rb") as fh:
        return tomllib.load(fh)


