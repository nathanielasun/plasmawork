"""Capsule save/reload.

Ships a real ``.lxp/`` directory format that satisfies the Phase 2 gate
("portable, inspectable, reloadable, exportable"). The writer here is the
single producer of capsule artifacts and is responsible for wiring in
every Phase 2 subsystem:

* Phase 2A — canonical ``manifest.toml`` (Pydantic ``Manifest``) and HDF5
  ``results/diagnostics.h5``. JSON is kept as a sidecar for legacy tools.
* Phase 2B — full provenance triad: ``ProvenanceLock`` (TOML) +
  ``environment.yaml`` (pip freeze + system info) + append-only
  ``agent_trace.md`` (``AgentTraceWriter``).
* Phase 2C — the saved capsule is the input to ``export_capsule`` and
  ``fork_capsule``; both rely on this writer's structural output.

Carries ``agent_error_patterns.md`` "Building writers without wiring
producers" — every Phase 2B writer MUST be invoked from this function.

Layout (plan §7.1):

    <name>.lxp/
      manifest.toml             — capsule metadata + format version (v0.1)
      model/model_spec.yaml     — copy of the experiment's ModelSpec
      configs/run_config.yaml   — Experiment + RunConfig + BackendConfig
      results/
        diagnostics.h5          — canonical bulk data (Phase 2A, ADR-0002)
        diagnostics.json        — sidecar for non-HDF5 readers
      provenance/
        provenance.lock         — Phase 2B ProvenanceLock (TOML)
        environment.yaml        — Phase 2B capture_environment()
        agent_trace.md          — Phase 2B AgentTraceWriter (append-only)
      paper_sources/, src/{generated,user_edits,kernels}/, data/,
      validation/, notebooks/   — created empty with .gitkeep markers
      README.md                 — autogenerated capsule summary
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from simworkbench import __version__ as workbench_version
from simworkbench.experiment import Experiment
from simworkbench.model_spec import to_dict as model_spec_to_dict
from simworkbench.paths import is_under_workbench, simulation_capsules_root
from simworkbench.runtime.runner import RunResult

CAPSULE_FORMAT_VERSION = "0.1"


@dataclass
class LoadedCapsule:
    """Parsed capsule + the run result it carries.

    Phase 1 keeps this lightweight: the experiment is reconstructable, the
    diagnostics are returned as plain dicts. Phase 2 will add a richer
    handle with capsule-level operations (fork, export, validate).
    """

    path: Path
    name: str
    format_version: str
    experiment: Experiment
    diagnostics: dict[str, list[float]]
    placeholders: list[str]
    final_simulation_time: float
    state: str
    elapsed_seconds: float
    provenance: dict[str, Any]


# ---------------------------------------------------------------------------
# Save
# ---------------------------------------------------------------------------


def save_capsule(
    *,
    experiment: Experiment,
    result: RunResult,
    name: str | None = None,
    base: Path | None = None,
) -> Path:
    """Write a capsule for ``experiment`` + ``result``. Return its directory.

    Validates the target path is under the four allowed workbench roots
    BEFORE creating any directories — honors `agent_error_patterns.md`
    "Side-effecting before validating".
    """
    capsule_name = name or _default_capsule_name(experiment, result)
    if not capsule_name.endswith(".lxp"):
        capsule_name = f"{capsule_name}.lxp"
    if base is None:
        base = simulation_capsules_root()
    target = Path(base) / capsule_name

    # Validate first; only then create.
    if not is_under_workbench(target):
        raise PermissionError(
            f"Refusing to save capsule outside workbench-managed roots: {target}"
        )
    target.mkdir(parents=True, exist_ok=True)

    # Manifest — Phase 2A canonical schema (Pydantic Manifest model).
    from simworkbench.serialization.manifest import (
        CapsuleSection,
        Manifest,
        ModelSection,
        RuntimeSection,
        write_manifest,
    )

    manifest = Manifest(
        capsule=CapsuleSection(
            name=capsule_name.removesuffix(".lxp"),
            format_version=CAPSULE_FORMAT_VERSION,
            workbench_version=workbench_version,
            created_at=_utc_now_iso(),
        ),
        model=ModelSection(
            name=experiment.model_spec.model.name,
            domain=experiment.model_spec.model.domain,
            schema_version=experiment.model_spec.schema_version,
        ),
        runtime=RuntimeSection(
            backend=experiment.backend_config.name,
            default_seed=experiment.run_config.seed,
            final_state=result.state.value,
            final_simulation_time_seconds=result.final_simulation_time,
            elapsed_seconds=result.elapsed_seconds,
            placeholder_used=bool(result.placeholders),
            placeholders=list(result.placeholders),
        ),
    )
    write_manifest(manifest, target / "manifest.toml")

    # Model spec.
    (target / "model").mkdir(parents=True, exist_ok=True)
    (target / "model" / "model_spec.yaml").write_text(
        yaml.safe_dump(model_spec_to_dict(experiment.model_spec), sort_keys=False, indent=2),
        encoding="utf-8",
    )

    # Run / backend / diagnostic config.
    (target / "configs").mkdir(parents=True, exist_ok=True)
    (target / "configs" / "run_config.yaml").write_text(
        yaml.safe_dump(experiment.to_dict(), sort_keys=False, indent=2),
        encoding="utf-8",
    )

    # Results — JSON in Phase 1; HDF5/Zarr in Phase 2 per ADR-0002.
    (target / "results").mkdir(parents=True, exist_ok=True)
    (target / "results" / "diagnostics.json").write_text(
        json.dumps(
            {
                "run_id": result.run_id,
                "state": result.state.value,
                "elapsed_seconds": result.elapsed_seconds,
                "final_simulation_time": result.final_simulation_time,
                "diagnostics": {k: list(v) for k, v in result.diagnostics.items()},
                "placeholders": list(result.placeholders),
            },
            indent=2,
        ),
        encoding="utf-8",
    )

    # HDF5 sidecar for the same diagnostics — Phase 2A authoritative bulk
    # format per ADR-0002 (Accepted). The JSON above is preserved for
    # tools that don't read HDF5.
    from simworkbench.serialization.bulk_data import write_diagnostics_h5

    write_diagnostics_h5(
        result.diagnostics,
        target / "results" / "diagnostics.h5",
        metadata={
            "run_id": result.run_id,
            "state": result.state.value,
            "elapsed_seconds": result.elapsed_seconds,
            "final_simulation_time_seconds": result.final_simulation_time,
            "placeholder_used": bool(result.placeholders),
            # Persist the full placeholder list, not just the boolean.
            # Carries `agent_error_patterns.md` "Serializer drops
            # semantic fields when writing the canonical format" — an
            # HDF5-only capsule reload had been losing the names.
            "placeholders": list(result.placeholders),
        },
    )

    # Phase 2B provenance triad — `provenance.lock` (TOML) + environment.yaml
    # (pip freeze + system) + `agent_trace.md` (append-only). Honors
    # `agent_error_patterns.md` "Building writers without wiring producers":
    # the producer (this function) MUST invoke every Phase 2B writer; if
    # someone adds a new triad member, this is the call site that picks it up.
    import platform as _platform
    import sys as _sys

    from simworkbench.provenance import (
        AgentTraceWriter,
        ProvenanceLock,
        write_environment,
        write_lock,
    )
    from simworkbench.provenance.sources import SourceRegistry

    (target / "provenance").mkdir(parents=True, exist_ok=True)
    # Empty the empty subtrees BEFORE hashing so the source-aggregate hash is
    # stable across saves of the same content (the .gitkeep files are part of
    # the capsule identity).
    for empty in (
        "paper_sources",
        "src/generated",
        "src/user_edits",
        "src/kernels",
        "data",
        "validation",
        "notebooks",
    ):
        (target / empty).mkdir(parents=True, exist_ok=True)
        (target / empty / ".gitkeep").touch()

    model_spec_hash = SourceRegistry(target).aggregate_hash(subtrees=("model",))
    lock = ProvenanceLock(
        workbench_version=workbench_version,
        python_version=_sys.version.split()[0],
        platform=_platform.platform(),
        capsule_format_version=CAPSULE_FORMAT_VERSION,
        run_id=result.run_id,
        base_seed=experiment.run_config.seed,
        backend=experiment.backend_config.name,
        model_spec_hash=model_spec_hash,
        placeholders=list(result.placeholders),
        parent_capsule_hash="",
        created_at=_utc_now_iso(),
    )
    write_lock(lock, target / "provenance" / "provenance.lock")
    write_environment(target / "provenance" / "environment.yaml")

    # Append-only agent_trace.md — `AgentTraceWriter` initializes the file
    # with the header on first call and appends one entry per save. Re-saving
    # the same capsule appends a new entry rather than overwriting (carries
    # `agent_error_patterns.md` "Append-only files written non-appendingly").
    trace = AgentTraceWriter(target / "provenance" / "agent_trace.md")
    trace.append(
        agent="simworkbench.serialization.capsule.save_capsule",
        action="saved capsule",
        files_touched=("manifest.toml", "results/diagnostics.h5"),
        notes=(
            f"workbench={workbench_version} format={CAPSULE_FORMAT_VERSION} "
            f"run_id={result.run_id} backend={experiment.backend_config.name}"
        ),
    )

    # Top-level README.
    readme = (
        f"# {capsule_name}\n\n"
        f"Workbench capsule, format v{CAPSULE_FORMAT_VERSION} (Phase 2A schema, "
        "ADR-0002 Accepted).\n\n"
        f"- Model: `{experiment.model_spec.model.name}` — domain "
        f"`{experiment.model_spec.model.domain}`\n"
        f"- Backend: `{experiment.backend_config.name}`\n"
        f"- Final state: `{result.state.value}`, "
        f"t_final = {result.final_simulation_time:.6g} s\n"
        f"- Placeholder rates used: {bool(result.placeholders)}"
        f" — {list(result.placeholders)}\n\n"
        "Bulk diagnostics are at `results/diagnostics.h5` (HDF5); a JSON "
        "sidecar at `results/diagnostics.json` is preserved for non-HDF5 tools.\n"
    )
    (target / "README.md").write_text(readme, encoding="utf-8")

    return target


