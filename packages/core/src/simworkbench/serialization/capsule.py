# Load
# ---------------------------------------------------------------------------


def load_capsule(path: str | Path) -> LoadedCapsule:
    """Read a capsule directory and return a ``LoadedCapsule``."""
    capsule_dir = Path(path).resolve()
    if not capsule_dir.is_dir():
        raise FileNotFoundError(f"Capsule directory not found: {capsule_dir}")

    manifest_path = capsule_dir / "manifest.toml"
    if not manifest_path.is_file():
        raise FileNotFoundError(
            f"No manifest.toml under {capsule_dir}; not a capsule directory."
        )
    manifest = _read_toml(manifest_path)

    capsule_section = manifest.get("capsule", {})
    fmt_version = capsule_section.get("format_version", "0.0")
    if fmt_version != CAPSULE_FORMAT_VERSION:
        raise ValueError(
            f"Unsupported capsule format_version {fmt_version!r}; "
            f"this build understands {CAPSULE_FORMAT_VERSION!r}. "
            "Capsule migrations land in Phase 2."
        )

    # Experiment lives at configs/run_config.yaml (it serializes the full
    # Experiment, ModelSpec inlined, by design of Workstream 1A).
    run_config_path = capsule_dir / "configs" / "run_config.yaml"
    if not run_config_path.is_file():
        raise FileNotFoundError(f"No configs/run_config.yaml under {capsule_dir}.")
    experiment = Experiment.load_yaml(run_config_path)

    # Diagnostics — HDF5 is canonical (Phase 2A); JSON sidecar is the
    # fallback for legacy or partial capsules. We read scalar metadata
    # (run_id, state, elapsed_seconds, final_simulation_time, placeholders)
    # from the JSON sidecar when available so the LoadedCapsule shape stays
    # complete regardless of which path was canonical.
    h5_path = capsule_dir / "results" / "diagnostics.h5"
    json_path = capsule_dir / "results" / "diagnostics.json"
    diagnostics: dict[str, list[float]] = {}
    payload: dict[str, Any] = {}
    if h5_path.is_file():
        from simworkbench.serialization.bulk_data import read_diagnostics_h5

        h5_data, h5_meta = read_diagnostics_h5(h5_path)
        diagnostics = {k: v.tolist() for k, v in h5_data.items()}
        payload.update(h5_meta)
        # ``placeholders`` is stored as a vlen-string list in HDF5; the
        # reader returns ``list[str]``. We coerce empty-string elements
        # away to keep the contract clean (an empty token list reads
        # back as ``[]`` rather than ``[""]``).
        if "placeholders" in payload and isinstance(payload["placeholders"], list):
            payload["placeholders"] = [
                str(p) for p in payload["placeholders"] if p
            ]
    if json_path.is_file():
        json_payload = json.loads(json_path.read_text(encoding="utf-8"))
        if not diagnostics:
            diagnostics = {
                k: list(v) for k, v in json_payload.get("diagnostics", {}).items()
            }
        # Sidecar metadata fills in scalars HDF5 didn't carry.
        for key in (
            "run_id",
            "state",
            "elapsed_seconds",
            "final_simulation_time",
            "placeholders",
        ):
            payload.setdefault(key, json_payload.get(key))
    if not h5_path.is_file() and not json_path.is_file():
        raise FileNotFoundError(
            f"No diagnostics under {capsule_dir}/results/ "
            "(expected diagnostics.h5 or diagnostics.json)."
        )

    provenance_path = capsule_dir / "provenance" / "provenance.lock"
    provenance = _read_toml(provenance_path) if provenance_path.is_file() else {}

    final_simulation_time_meta = (
        payload.get("final_simulation_time")
        if "final_simulation_time" in payload
        else payload.get("final_simulation_time_seconds", 0.0)
    )
    return LoadedCapsule(
        path=capsule_dir,
        name=capsule_section.get("name", capsule_dir.stem),
        format_version=fmt_version,
        experiment=experiment,
        diagnostics=diagnostics,
        placeholders=list(payload.get("placeholders", []) or []),
        final_simulation_time=float(final_simulation_time_meta or 0.0),
        state=str(payload.get("state") or "unknown"),
        elapsed_seconds=float(payload.get("elapsed_seconds") or 0.0),
        provenance=provenance,
    )


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _default_capsule_name(experiment: Experiment, result: RunResult) -> str:
    base = experiment.model_spec.model.name.replace(" ", "_")
    return f"{base}-{result.run_id[:8]}"


def _utc_now_iso() -> str:
    from datetime import UTC, datetime

    return datetime.now(UTC).isoformat(timespec="microseconds")


def _read_toml(path: Path) -> dict[str, Any]:
    """Parse TOML using the stdlib ``tomllib`` (Python 3.11+)."""
    import tomllib

    with path.open("rb") as fh:
        return tomllib.load(fh)


